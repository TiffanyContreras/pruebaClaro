CREATE TABLE ORDERS(
    ID NUMBER  PRIMARY KEY,
    ORDER_NUMBER VARCHAR2(50) NOT NULL,
    CLIENT_ID NUMBER NOT NULL,
    SERVICE_TYPE VARCHAR2(100) NOT NULL,
    STATUS VARCHAR2(30) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    
    CONSTRAINT UK_ORDERS_ORDER_NUMBER UNIQUE (ORDER_NUMBER)
);


CREATE TABLE ORDER_HISTORY(
    ID NUMBER PRIMARY KEY,
    ORDER_ID NUMBER NOT NULL,
    PREVIOUS_STATUS VARCHAR2(30),
    NEW_STATUS VARCHAR2(30) NOT NULL,
    CHANGED_AT TIMESTAMP NOT NULL,
    CONSTRAINT FK_HISTORY_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ID)
);

CREATE SEQUENCE SEQ_ORDERS
START WITH 1
INCREMENT BY 1;

CREATE SEQUENCE SEQ_ORDER_HISTORY
START WITH 1
INCREMENT BY 1;

CREATE INDEX IDX_ORDERS_CLIENTE_ID
ON ORDERS(CLIENT_ID);

CREATE INDEX IDX_ORDER_HISTORY_ORDER_ID
ON ORDER_HISTORY(ORDER_ID);


SELECT * FROM ORDERS;

